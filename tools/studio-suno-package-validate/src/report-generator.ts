import * as fs from 'fs';
import * as path from 'path';
import { ValidationReport } from './types.js';

/**
 * Generate markdown report from validation results
 */
export function generateMarkdownReport(report: ValidationReport): string {
  const lines: string[] = [];
  
  lines.push('# Suno Job Package Validation Report');
  lines.push('');
  lines.push(`**Validated:** ${report.timestamp}`);
  lines.push(`**Job Directory:** \`${report.job_dir}\``);
  lines.push('');
  
  lines.push('## Summary');
  lines.push('');
  lines.push(`- **Total Checks:** ${report.summary.total_checks}`);
  lines.push(`- **Passed:** ${report.summary.passed}`);
  lines.push(`- **Failed:** ${report.summary.failed}`);
  lines.push(`- **Overall:** ${report.summary.all_passed ? '✅ PASS' : '❌ FAIL'}`);
  lines.push('');
  
  lines.push('## Validation Checks');
  lines.push('');
  
  let checkNumber = 1;
  
  for (const [key, check] of Object.entries(report.checks)) {
    const status = check.passed ? '✅ PASS' : '❌ FAIL';
    const title = key.replace(/_/g, ' ').replace(/\b\w/g, l => l.toUpperCase());
    
    lines.push(`### ${checkNumber}. ${title}`);
    lines.push('');
    lines.push(`**Status:** ${status}`);
    lines.push(`**Message:** ${check.message}`);
    
    if (check.details) {
      lines.push('');
      lines.push(`**Details:**`);
      lines.push('```');
      lines.push(check.details);
      lines.push('```');
    }
    
    lines.push('');
    checkNumber++;
  }
  
  return lines.join('\n');
}

