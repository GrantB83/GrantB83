/**
 * Generate manifest.json
 */
export function generateManifest(report: ValidationReport, outdir: string): object {
  return {
    tool: 'studio-suno-package-validate',
    version: '1.0.0',
    generated_at: report.timestamp,
    job_dir: report.job_dir,
    output_dir: outdir,
    validation_result: {
      all_passed: report.summary.all_passed,
      passed: report.summary.passed,
      failed: report.summary.failed,
      total: report.summary.total_checks
    },
    outputs: {
      report_json: 'report.json',
      report_md: 'report.md',
      approval_md: 'APPROVAL.md',
      manifest_json: 'manifest.json'
    }
  };
}

/**
 * Write all output files
 */
export async function writeReports(
  report: ValidationReport,
  outdir: string
): Promise<void> {
  // Ensure output directory exists
  if (!fs.existsSync(outdir)) {
    fs.mkdirSync(outdir, { recursive: true });
  }
  
  // Write report.json
  fs.writeFileSync(
    path.join(outdir, 'report.json'),
    JSON.stringify(report, null, 2)
  );
  
  // Write report.md
  const markdown = generateMarkdownReport(report);
  fs.writeFileSync(
    path.join(outdir, 'report.md'),
    markdown
  );
  
  // Write APPROVAL.md
  const approval = generateApprovalDoc();
  fs.writeFileSync(
    path.join(outdir, 'APPROVAL.md'),
    approval
  );
  
  // Write manifest.json
  const manifest = generateManifest(report, outdir);
  fs.writeFileSync(
    path.join(outdir, 'manifest.json'),
    JSON.stringify(manifest, null, 2)
  );
}
